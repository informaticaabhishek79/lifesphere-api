import { boolean, date, index, pgTable, primaryKey, text, uuid, varchar } from 'drizzle-orm/pg-core';
import { createdAt, deletedAt, id, ts, updatedAt } from './_columns';
import { caseEventKind, consumerCaseStatus, draftSource, officialChannelKind } from './enums';
import { users } from './identity';
import { homeInventoryItems, households } from './lifeos';
import { attachments } from './platform';

/** Curated directory of official complaint / civic channels, maintained by content admins. */
export const officialChannels = pgTable(
  'official_channels',
  {
    id: id(),
    kind: officialChannelKind('kind').notNull(),
    name: varchar('name', { length: 160 }).notNull(),
    jurisdiction: varchar('jurisdiction', { length: 120 }).notNull().default('India'),
    /** Optional: categories this channel handles, e.g. ['ecommerce','telecom'] or ['streetlight']. */
    topics: text('topics').array(),
    url: varchar('url', { length: 400 }),
    phone: varchar('phone', { length: 40 }),
    description: text('description'),
    lastReviewedOn: date('last_reviewed_on'),
    active: boolean('active').notNull().default(true),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [index('official_channel_kind_idx').on(t.kind, t.active)],
);

export const purchases = pgTable(
  'purchases',
  {
    id: id(),
    ownerUserId: uuid('owner_user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    householdId: uuid('household_id').references(() => households.id, { onDelete: 'set null' }),
    inventoryItemId: uuid('inventory_item_id').references(() => homeInventoryItems.id, { onDelete: 'set null' }),
    productCategory: varchar('product_category', { length: 60 }).notNull(),
    brand: varchar('brand', { length: 60 }),
    model: varchar('model', { length: 80 }),
    purchaseDate: date('purchase_date'),
    retailerName: varchar('retailer_name', { length: 120 }),
    warrantyExpiresOn: date('warranty_expires_on'),
    returnDeadline: date('return_deadline'),
    serviceReference: varchar('service_reference', { length: 80 }),
    notes: text('notes'),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
    deletedAt: deletedAt(),
  },
  (t) => [index('purchase_owner_idx').on(t.ownerUserId), index('purchase_warranty_idx').on(t.warrantyExpiresOn)],
);

export const consumerCases = pgTable(
  'consumer_cases',
  {
    id: id(),
    ownerUserId: uuid('owner_user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    purchaseId: uuid('purchase_id').references(() => purchases.id, { onDelete: 'set null' }),
    title: varchar('title', { length: 200 }).notNull(),
    counterpartyName: varchar('counterparty_name', { length: 120 }),
    category: varchar('category', { length: 60 }),
    status: consumerCaseStatus('status').notNull().default('draft'),
    /** Reference number exactly as entered by the user; never generated by the platform. */
    externalReference: varchar('external_reference', { length: 80 }),
    officialChannelId: uuid('official_channel_id').references(() => officialChannels.id, { onDelete: 'set null' }),
    submittedAt: ts('submitted_at'),
    nextFollowUpOn: date('next_follow_up_on'),
    resolutionNote: text('resolution_note'),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
    deletedAt: deletedAt(),
  },
  (t) => [
    index('case_owner_idx').on(t.ownerUserId, t.status),
    index('case_followup_idx').on(t.nextFollowUpOn),
  ],
);

export const consumerCaseEvents = pgTable(
  'consumer_case_events',
  {
    id: id(),
    caseId: uuid('case_id')
      .notNull()
      .references(() => consumerCases.id, { onDelete: 'cascade' }),
    kind: caseEventKind('kind').notNull(),
    occurredOn: date('occurred_on').notNull(),
    description: varchar('description', { length: 1000 }).notNull(),
    createdAt: createdAt(),
  },
  (t) => [index('case_event_case_idx').on(t.caseId, t.occurredOn)],
);

export const complaintDrafts = pgTable(
  'complaint_drafts',
  {
    id: id(),
    caseId: uuid('case_id')
      .notNull()
      .references(() => consumerCases.id, { onDelete: 'cascade' }),
    body: text('body').notNull(),
    source: draftSource('source').notNull(),
    aiModel: varchar('ai_model', { length: 80 }),
    /** User must approve before marking the case as submitted by them. */
    approvedAt: ts('approved_at'),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [index('draft_case_idx').on(t.caseId)],
);

export const caseAttachments = pgTable(
  'case_attachments',
  {
    caseId: uuid('case_id')
      .notNull()
      .references(() => consumerCases.id, { onDelete: 'cascade' }),
    attachmentId: uuid('attachment_id')
      .notNull()
      .references(() => attachments.id, { onDelete: 'cascade' }),
  },
  (t) => [primaryKey({ columns: [t.caseId, t.attachmentId] })],
);
